"""The protocol 2.0 wire contract core mirrors is produced by this code, and current.

``packages/cruxible-provider-runtime/tests/fixtures/provider_runtime_contract_v2.json``
is what core vendors and pins (it keeps its own copy of the wire models and
does not import this runtime). The file is generated by
``scripts/export_runtime_contract.py``; this asserts that regenerating it is a
no-op, and that its vectors mean what they say against this runtime.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest
from cruxible_provider_runtime.errors import RefusalCode, RefusalError
from cruxible_provider_runtime.protocol import parse_result_envelope, parse_run_context

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from scripts.export_runtime_contract import TARGET, render  # noqa: E402


def _fixture() -> dict[str, object]:
    document: dict[str, object] = json.loads(TARGET.read_text(encoding="utf-8"))
    return document


def _bytes(value: object) -> bytes:
    return json.dumps(value, separators=(",", ":")).encode("utf-8")


def test_the_committed_fixture_is_what_the_exporter_writes() -> None:
    assert TARGET.read_bytes() == render(), "run scripts/export_runtime_contract.py"


def test_the_valid_vectors_round_trip_exactly() -> None:
    vectors = _fixture()["valid_vectors"]
    assert isinstance(vectors, dict)
    context = parse_run_context(_bytes(vectors["run_context"]))
    assert json.loads(context.model_dump_json()) == vectors["run_context"]
    for payload in vectors["results"].values():
        envelope = parse_result_envelope(_bytes(payload))
        assert json.loads(envelope.model_dump_json()) == payload


@pytest.mark.parametrize(
    ("name", "parse", "code"),
    [
        ("context_unknown_field", parse_run_context, RefusalCode.UNKNOWN_RUN_CONTEXT_FIELD),
        ("context_protocol_1", parse_run_context, RefusalCode.UNSUPPORTED_PROTOCOL),
        ("result_missing_output", parse_result_envelope, RefusalCode.PROVIDER_PROTOCOL_VIOLATION),
        ("result_protocol_1", parse_result_envelope, RefusalCode.UNSUPPORTED_PROTOCOL),
    ],
)
def test_the_invalid_vectors_refuse_with_their_codes(
    name: str, parse: object, code: RefusalCode
) -> None:
    vectors = _fixture()["invalid_vectors"]
    assert isinstance(vectors, dict)
    with pytest.raises(RefusalError) as exc:
        parse(_bytes(vectors[name]))  # type: ignore[operator]
    assert exc.value.code is code


def test_the_reserved_codes_are_exactly_the_runtimes() -> None:
    assert _fixture()["runtime_refusal_codes"] == sorted(code.value for code in RefusalCode)
